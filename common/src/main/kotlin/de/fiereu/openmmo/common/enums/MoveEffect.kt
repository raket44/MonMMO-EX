  /**
   * Whether the battle engine actually resolves this effect, as opposed to merely recording it.
   *
   * Every move is imported from pokeemerald-expansion so its data is its own, but the engine was
   * written against a handful of stat-change effects and plain damage. Everything else is carried
   * faithfully and does nothing in battle yet, which is worth knowing before a move is presented as
   * working. Mirrors [de.fiereu.openmmo.common.enums.Ability.mechanicsImplemented].
   */
